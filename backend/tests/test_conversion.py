# --- variant comparison --------------------------------------------------------


def test_variant_sweep_never_touches_source(engine, source):
    make_video(source["root"] / "clips" / "clip.mp4")
    scan_source(engine, source["id"], source["root"])
    profile = _make_profile(engine)
    file_row = _file_row(engine, "clips/clip.mp4")
    original_size = (source["root"] / "clips" / "clip.mp4").stat().st_size

    variants = [{"crf": 24}, {"max_dimension": 100, "crf": 30}]
    job = _run_job(
        engine, "file", file_row.id,
        {"file_id": file_row.id, "profile_id": profile["id"], "mode": "test", "variants": variants},
    )

    assert job["status"] == "completed"
    assert (source["root"] / "clips" / "clip.mp4").exists()
    assert (source["root"] / "clips" / "clip.mp4").stat().st_size == original_size

    variant_files = sorted(p.name for p in (source["root"] / "clips").glob("clip.variant-*.mp4"))
    assert variant_files == ["clip.variant-crf24.mp4", "clip.variant-d100-crf30.mp4"]

    items = service.get_job_items(engine, job["id"])
    assert len(items) == 2
    assert all(item["status"] == "completed" for item in items)

    row = _file_row(engine, "clips/clip.mp4")
    assert row.converted_at is None


# --- skip-processed and directory recursion ------------------------------------


def test_directory_scope_skip_processed(engine, source):
    make_video(source["root"] / "clips" / "a.mp4")
    make_video(source["root"] / "clips" / "b.mp4")
    scan_source(engine, source["id"], source["root"])
    profile = _make_profile(engine)

    a_row = _file_row(engine, "clips/a.mp4")
    with engine.begin() as conn:
        conn.execute(
            text("UPDATE files SET converted_at = :now WHERE id = :id"),
            {"now": "2020-01-01T00:00:00+00:00", "id": a_row.id},
        )

    job = _run_job(
        engine, "directory", "clips",
        {"path": "clips", "profile_id": profile["id"], "mode": "production", "skip_processed": True},
    )

    assert job["status"] == "completed"
    items = service.get_job_items(engine, job["id"])
    statuses = sorted(item["status"] for item in items)
    assert statuses == ["completed", "skipped"]


def test_directory_recursive_conversion_excludes_test_artifacts(engine, source):
    make_video(source["root"] / "top.mp4")
    make_video(source["root"] / "sub" / "nested.mp4")
    (source["root"] / "sub" / "already.original.mp4").write_bytes(b"0")
    (source["root"] / "sub" / "already.variant-crf28.mp4").write_bytes(b"0")
    scan_source(engine, source["id"], source["root"])
    profile = _make_profile(engine)

    job = _run_job(
        engine, "source", None,
        {"path": "", "profile_id": profile["id"], "mode": "production", "skip_processed": True},
    )

    assert job["status"] == "completed"
    items = service.get_job_items(engine, job["id"])
    assert len(items) == 2  # top.mp4 + sub/nested.mp4 only; the two artifacts are excluded entirely

    assert (source["root"] / "top.mp4").exists()
    assert (source["root"] / "sub" / "nested.mp4").exists()


